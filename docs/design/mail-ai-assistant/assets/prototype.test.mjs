test('AI failure, original-version retry, and intentional new-version rerun keep distinct histories', { timeout: 45000 }, async t => {
  const f = await fixture(t), { view } = f;
  await scenario(view,'task_failure');
  const original = await state(view), initialRun = original.runs.find(r=>r.id === 'airun_todo_extraction');
  await click(view,'[data-action="navigate"][data-view="config"]');
  await click(view,action('config-tab','tasks'));
  await click(view,action('edit-task','task_todo_extraction'));
  await fill(view,'#task-instructions','提取待办，并逐项引用原文。不要猜测日期或负责人。');
  await click(view,'#task-form button[type="submit"]');
  assert.equal((await state(view)).results.length,5,'Editing has no implicit rerun');
  await click(view,'[data-action="navigate"][data-view="runs"]');
  await fill(view,'#run-kind','ai');
  assert.equal(await view.cdp.evaluate('!!document.querySelector("#run-status option[value=partial]")'),false);
  await click(view,action('run-detail','airun_todo_extraction'));
  await screenshot(view,'desktop-task-failure');
  await click(view,action('retry-run','airun_todo_extraction'));
  await completed(view);
  let after = await state(view), retry = after.runs.find(r=>r.id === initialRun.id);
  assert.equal(retry.taskVersionId,initialRun.taskVersionId); assert.equal(retry.trigger,initialRun.trigger);
  assert.equal(retry.attempt,4); assert.equal(after.results.length,6);
  const retriedResult = after.results.find(r=>r.id === retry.resultId);
  assert.equal(retriedResult.output.items[1].owner,null); assert.equal(retriedResult.output.items[1].dueDate,null);
  await click(view,action('open-result',retry.resultId));
  assert.match(await view.cdp.evaluate('document.querySelector(".result-output").innerText'),/未提供/);
  await click(view,action('run-message',retry.messageId));
  await completed(view);
  after = await state(view);
  const versions = after.results.filter(r=>r.messageId === retry.messageId && r.taskId === retry.taskId);
  assert.equal(versions.length,2); assert.notEqual(versions[0].taskVersionId,versions[1].taskVersionId);
  assert.ok(after.results.find(r=>r.id === 'res_summary'),'Other successful output remains');
  assert.equal(after.runs.filter(r=>r.kind === 'ai').some(r=>r.status === 'partial'),false);
  await assertClean(f);
});

