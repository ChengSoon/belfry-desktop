import assert from "node:assert/strict";
import test from "node:test";
import { uiFixture, click, clickText, fill, intact, resize, waitFor, clickOption } from "./production-uiFixture.mjs";
import { englishPanel, switchLanguage } from "./i18n-browser-support.mjs";

test('English plugin marketplace and template dialog fit 720x480 and update native plugin context', async t => {
  const {view,baseline} = await uiFixture(t,{nativeExtension:"localStorage.setItem('belfry.locale.v1','en');"});
  await resize(view,720,480);
  await click(view,'button[title^="Settings"]');
  await clickText(view,'Plugins','.settings-nav');
  await waitFor(view,"!!document.querySelector('.plugins-row-details-toggle')");
  await click(view,'.plugins-row-details-toggle');
  await englishPanel(view,'.pi-plugins');
  await waitFor(view,"__productionQA.pluginContext?.locale === 'en' && __productionQA.pluginContext?.appearance.locale === 'en'");
  await click(view,'#plugins-tab-market');
  await waitFor(view,"!!document.querySelector('.plugins-card-hit')");
  await englishPanel(view,'.pi-plugins');
  await click(view,'.plugins-card-hit');
  await waitFor(view,"!!document.querySelector('.plugins-sheet[role=dialog]')");
  await englishPanel(view,'.plugins-sheet');
  await click(view,'.plugins-sheet-head button');
  await click(view,'.plugins-market-settings-control button[aria-haspopup=listbox]');
  await clickOption(view,'Custom online marketplace');
  await fill(view,'input[aria-label="Catalog URL"]','https://synthetic.invalid/catalog.json');
  await clickText(view,'Save and connect','.plugins-market-settings');
  await waitFor(view,"__productionQA.calls.some(call => call.args?.method === 'management.source' && call.args.params.settings.pluginMarketCustomUrl === 'https://synthetic.invalid/catalog.json')");
  await englishPanel(view,'.pi-plugins');
  await click(view,'.plugins-header-menu');
  await clickText(view,'Create a plugin from a template','.plugins-menu');
  await waitFor(view,"!!document.querySelector('.plugins-modal input')");
  await fill(view,'.plugins-modal input','Notes and references');
  await view.cdp.evaluate("void (window.qaPluginName = document.querySelector('.plugins-modal input'))");
  await englishPanel(view,'.plugins-modal');
  await switchLanguage(view,'zh-CN');
  await waitFor(view,"__productionQA.pluginContext?.locale === 'zh-CN'");
  await switchLanguage(view,'en');
  await waitFor(view,"__productionQA.pluginContext?.locale === 'en'");
  assert.equal(await view.cdp.evaluate("qaPluginName === document.querySelector('.plugins-modal input') && qaPluginName.value === 'Notes and references'"),true);
  await englishPanel(view,'.plugins-modal');
  await clickText(view,'Cancel','.plugins-modal-actions');
  await waitFor(view,"!document.querySelector('.plugins-modal')");
  await click(view,'button[title="Close settings"]');
  await intact(view,baseline);
});
