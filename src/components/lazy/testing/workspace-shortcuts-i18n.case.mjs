import assert from "node:assert/strict";
import test from "node:test";
import { uiFixture, click, clickText, fill, intact, press, resize, waitFor } from "./production-uiFixture.mjs";
import { englishPanel, openAction, switchLanguage } from "./i18n-browser-support.mjs";

const nativeExtension = "localStorage.setItem('belfry.locale.v1', 'en');";

test('English project and SSH forms keep drafts and primary actions usable at 720x480', async t => {
  const {view,baseline} = await uiFixture(t, {nativeExtension});
  await resize(view,720,480);
  await click(view,'.project-trigger');
  await clickText(view,'Project settings','.popover--project');
  await waitFor(view,"!!document.querySelector('.project-profile')");
  await fill(view,'input[aria-label="Project group"]','Production projects');
  // The group combobox owns an open suggestions layer above the launch control.
  await press(view,'Escape');
  await waitFor(view,"document.querySelector('input[aria-label=\"Project group\"]')?.getAttribute('aria-expanded') === 'false'");
  await clickText(view,'Launch settings','.project-profile');
  await fill(view,'input[aria-label="Project startup command"]','pnpm dev');
  await view.cdp.evaluate("void (window.qaProjectCommand = document.querySelector('input[aria-label=\"Project startup command\"]'))");
  await englishPanel(view,'.project-library');
  await switchLanguage(view,'zh-CN');
  await waitFor(view,"document.querySelector('.project-profile')?.textContent.includes('保存项目')");
  await switchLanguage(view,'en');
  await waitFor(view,"document.querySelector('.project-profile')?.textContent.includes('Save project')");
  assert.equal(await view.cdp.evaluate("qaProjectCommand === document.querySelector('input[aria-label=\"Project startup command\"]') && qaProjectCommand.value === 'pnpm dev'"),true);
  await clickText(view,'Save project','.project-profile');
  await waitFor(view,"JSON.parse(localStorage.getItem('belfry.project-catalog.v1')).entries.some(entry => entry.command === 'pnpm dev' && entry.group === 'Production projects')");
  await click(view,'button[aria-label="Close project settings"]');
  await waitFor(view,"!document.querySelector('.project-library')");
  await click(view,'button[title^="New session"]');
  await clickText(view,'SSH','.new-session-menu');
  await waitFor(view,"!!document.querySelector('.modal--ssh')");
  await fill(view,'input[aria-label="SSH host"]','example.test');
  await fill(view,'input[aria-label="SSH port"]','99999');
  await clickText(view,'Connect','.ssh-dialog__actions');
  await waitFor(view,"!!document.querySelector('.ssh-form__error')");
  await englishPanel(view,'.modal--ssh');
  await switchLanguage(view,'zh-CN');
  assert.match(await view.cdp.evaluate("document.querySelector('.ssh-form__error').textContent"),/\p{Script=Han}/u);
  await switchLanguage(view,'en');
  await englishPanel(view,'.modal--ssh');
  await fill(view,'input[aria-label="SSH port"]','22');
  await switchLanguage(view,'zh-CN');
  await switchLanguage(view,'en');
  assert.equal(await view.cdp.evaluate("document.querySelector('input[aria-label=\"SSH host\"]').value"),'example.test');
  await englishPanel(view,'.modal--ssh');
  await click(view,'button[aria-label="Close SSH connection dialog"]');
  await intact(view,baseline);
});

test('English shortcut settings retain the edit and save/reset without recreating terminals', async t => {
  const {view,baseline} = await uiFixture(t, {nativeExtension});
  await resize(view,720,480);
  await click(view,'button[title^="Settings"]');
  await clickText(view,'Shortcuts','.settings-nav');
  await waitFor(view,"!!document.querySelector('#shortcut-edit-new-shell')");
  await englishPanel(view,'.shortcut-settings');
  await click(view,'#shortcut-edit-new-shell');
  await waitFor(view,"!!document.querySelector('.shortcut-editor')");
  await clickText(view,'Disable','.shortcut-editor');
  await switchLanguage(view,'zh-CN');
  await switchLanguage(view,'en');
  await englishPanel(view,'.shortcut-settings');
  assert.match(await view.cdp.evaluate("document.querySelector('.shortcut-editor__preview').textContent"),/After saving/);
  await clickText(view,'Save','.shortcut-editor');
  await waitFor(view,"!document.querySelector('.shortcut-editor')");
  assert.equal(await view.cdp.evaluate("Object.values(JSON.parse(localStorage.getItem('belfry.shortcuts.v1'))).some(value => value && Object.hasOwn(value,'new-shell') && value['new-shell'] === null)"),true);
  await click(view,'#shortcut-reset-all');
  await waitFor(view,"!!document.querySelector('.shortcut-reset')");
  await englishPanel(view,'.shortcut-settings');
  await clickText(view,'Confirm restoring defaults','.shortcut-reset');
  await waitFor(view,"!document.querySelector('.shortcut-reset')");
  await click(view,'button[title="Close settings"]');
  await openAction(view,'open shortcuts');
  await waitFor(view,"!!document.querySelector('.modal--shortcut-guide')");
  await englishPanel(view,'.modal--shortcut-guide');
  await click(view,'#shortcut-tab-codex');
  await englishPanel(view,'.modal--shortcut-guide');
  await click(view,'.shortcut-guide__head button');
  await intact(view,baseline);
});
